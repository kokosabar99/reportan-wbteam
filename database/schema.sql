CREATE TABLE IF NOT EXISTS staff (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name TEXT NOT NULL UNIQUE, username TEXT UNIQUE,
 password_hash TEXT, role TEXT NOT NULL CHECK(role IN ('CS LINE','KAPTEN KASIR','CS LC','KASIR')),
 active BOOLEAN NOT NULL DEFAULT TRUE, can_manage BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS staff_full_name_ci ON staff (lower(full_name));
CREATE UNIQUE INDEX IF NOT EXISTS staff_username_ci ON staff (lower(username)) WHERE username IS NOT NULL;
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY,
 staff_id BIGINT NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 type TEXT NOT NULL, subtype TEXT, user_id TEXT, nominal BIGINT, proof TEXT,
 details JSONB NOT NULL DEFAULT '{}'::jsonb,
 status TEXT NOT NULL DEFAULT 'WAITING' CHECK(status IN ('WAITING','DONE')),
 created_by BIGINT NOT NULL REFERENCES staff(id),
 done_by BIGINT REFERENCES staff(id), done_note TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), done_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_reports_status ON reports(status,created_at);
CREATE INDEX IF NOT EXISTS idx_reports_user ON reports(user_id);
CREATE TABLE IF NOT EXISTS audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 staff_id BIGINT NOT NULL REFERENCES staff(id),
 action TEXT NOT NULL, report_id BIGINT REFERENCES reports(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
